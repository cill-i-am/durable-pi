import { createHash } from "node:crypto"
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { DatabaseSync } from "node:sqlite"
import { fileURLToPath } from "node:url"

import { format } from "oxfmt"

import formatting from "../oxfmt.config.ts"

const directory = new URL("../migrations/agent/", import.meta.url)
const database = new DatabaseSync(":memory:")
try {
  const versions = readdirSync(directory)
    .sort()
    .map((id) => {
      const sql = readFileSync(
        new URL(`${id}/migration.sql`, directory),
        "utf8"
      )
      database.exec(sql)
      return {
        id,
        checksum: createHash("sha256").update(sql).digest("hex"),
        statements: sql
          .split("--> statement-breakpoint")
          .map((value) => value.trim())
          .filter(Boolean),
      }
    })
  if (!versions.length) throw new Error("No generated agent migrations")
  const schema = database
    .prepare(
      "SELECT type,name,sql FROM sqlite_schema WHERE type IN ('table','index') AND name NOT LIKE 'sqlite_%' AND sql IS NOT NULL ORDER BY name"
    )
    .all()
  const destination = fileURLToPath(
    new URL("../src/storage/migration-manifest.ts", import.meta.url)
  )
  const { code: content, errors } = await format(
    destination,
    `// Generated by scripts/generate-agent-migration-manifest.mjs. Do not edit.\nexport const agentMigrationManifest = ${JSON.stringify({ versions, schema }, null, 2)} as const\n`,
    formatting
  )
  if (errors.length)
    throw new Error("Could not format agent migration manifest")
  if (process.argv.includes("--check")) {
    if (readFileSync(destination, "utf8") !== content)
      throw new Error(
        "Agent migration manifest is stale; regenerate it after drizzle-kit generate"
      )
  } else writeFileSync(destination, content)
} finally {
  database.close()
}
